<div class="terms-text mb-4">
    <h5 class="text-primary fw-bold">2. كيف نستخدم معلوماتك</h5>
    <ul>
        <li>تقديم خدمات الرأي الطبي الثاني</li>
        <li>مراجعة السجلات الطبية وتحليلها</li>
        <li>التواصل معك بشأن استشارتك</li>
        <li>تحسين وظائف المنصة</li>
