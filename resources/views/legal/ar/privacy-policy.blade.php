    <p>
        إذا كنت مقيمًا في الولايات المتحدة، فإن معلوماتك الصحية المحمية (PHI) تُعالَج وفقًا لقانون قابلية نقل التأمين الصحي والمساءلة (HIPAA).
    </p>

    <ul>
